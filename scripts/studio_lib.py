"""Procedural rendering helpers: wood, cork, plaster, leaves, books, props, light.
Everything in the study-room artwork is generated by code (no photos are used)."""
import math
import random

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFilter


# ----------------------------------------------------------------- noise & textures
def noise(w, h, sx, sy, seed):
    """Smooth value noise in 0..1; sx/sy = feature size in pixels along x / y."""
    rs = np.random.RandomState(seed)
    gw, gh = max(2, int(w / sx) + 2), max(2, int(h / sy) + 2)
    small = Image.fromarray((rs.rand(gh, gw) * 255).astype(np.uint8))
    big = small.resize((int(gw * sx), int(gh * sy)), Image.BICUBIC).crop((0, 0, w, h))
    return np.asarray(big).astype(np.float32) / 255.0


def fbm(w, h, base, seed, octaves=4, aniso=1.0):
    total, amp, norm = np.zeros((h, w), np.float32), 1.0, 0.0
    for o in range(octaves):
        s = max(1.0, base / (2 ** o))
        total += amp * noise(w, h, s * aniso, s, seed + o * 17)
        norm += amp
        amp *= 0.5
    return total / norm


def to_img(arr):
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8), "RGB")


def wood(w, h, seed=1, base=(150, 104, 66), plank=None, ring=34.0, dark=0.30):
    """Horizontal wood grain with plank seams."""
    y = np.arange(h, dtype=np.float32)[:, None] * np.ones((1, w), np.float32)
    warp = fbm(w, h, 220, seed, 3, aniso=3.5) * 26 + fbm(w, h, 60, seed + 5, 3, aniso=5) * 5
    rings = 0.5 + 0.5 * np.sin((y + warp) / ring * 2 * math.pi)
    rings = rings ** 1.6
    fibre = fbm(w, h, 5, seed + 9, 3, aniso=22)
    pores = noise(w, h, 3, 1.2, seed + 3)
    tone = 1.0 - dark * rings * 0.55 - 0.16 * fibre - 0.05 * pores + 0.10 * fbm(w, h, 400, seed + 11, 2)
    arr = np.stack([base[0] * tone, base[1] * tone, base[2] * tone], -1)
    img = to_img(arr)
    if plank:
        d = ImageDraw.Draw(img)
        rs = random.Random(seed)
        for py in range(plank, h, plank):
            d.line([(0, py), (w, py)], fill=(40, 24, 12), width=3)
            d.line([(0, py + 3), (w, py + 3)], fill=tuple(int(c * 1.12) for c in base), width=1)
        # per-plank tone shift
        out = np.asarray(img).astype(np.float32)
        for i, py in enumerate(range(0, h, plank)):
            out[py:py + plank] *= 0.94 + 0.12 * rs.random()
        img = to_img(out)
    return img


def cork(w, h, seed=7):
    base = np.array([196, 150, 102], np.float32)
    blotch = fbm(w, h, 160, seed, 4)
    fine = noise(w, h, 2, 2, seed + 2)
    mid = noise(w, h, 5, 5, seed + 4)
    dark_flecks = (fine > 0.80) | ((mid > 0.84) & (fine > 0.5))
    light_flecks = (noise(w, h, 3, 3, seed + 6) > 0.86)
    arr = base[None, None, :] * (0.86 + 0.28 * blotch)[..., None]
    arr = arr * (0.93 + 0.14 * mid)[..., None]
    arr[dark_flecks] *= np.array([0.55, 0.50, 0.45])
    arr[light_flecks] = arr[light_flecks] * 0.55 + np.array([232, 196, 146]) * 0.45
    # emboss for tiny relief
    g = fine
    relief = (np.roll(g, 1, 0) - np.roll(g, -1, 0) + np.roll(g, 1, 1) - np.roll(g, -1, 1)) * 18
    arr += relief[..., None]
    return to_img(arr)


def plaster(w, h, seed=3, base=(239, 227, 205)):
    low = fbm(w, h, 380, seed, 3)
    grain = noise(w, h, 2, 2, seed + 1)
    tone = 0.965 + 0.05 * low + 0.012 * grain
    arr = np.stack([base[0] * tone, base[1] * tone, base[2] * tone], -1)
    return to_img(arr)


def paper_tile(size=512, seed=21):
    fibre = noise(size, size, 2, 2, seed)
    low = fbm(size, size, 90, seed + 2, 3)
    tone = 0.93 + 0.05 * low + 0.03 * fibre
    arr = np.stack([255 * tone, 252 * tone, 244 * tone], -1)
    return to_img(arr)


# ----------------------------------------------------------------- compositing
def rgba(w, h):
    return Image.new("RGBA", (w, h), (0, 0, 0, 0))


def shadow_of(layer, blur=10, opacity=0.5, color=(30, 18, 8)):
    """Returns (shadow_layer, pad). The layer is padded so the blur is not clipped."""
    pad = int(blur * 3) + 2
    a = Image.new("L", (layer.size[0] + pad * 2, layer.size[1] + pad * 2), 0)
    a.paste(layer.getchannel("A"), (pad, pad))
    a = a.filter(ImageFilter.GaussianBlur(blur)).point(lambda v: int(v * opacity))
    s = Image.new("RGBA", a.size, color + (0,))
    s.putalpha(a)
    return s, pad


def put(canvas, layer, xy, shadow=(6, 10, 10, 0.45)):
    """Composite layer at xy (top-left) with an optional drop shadow."""
    x, y = int(xy[0]), int(xy[1])
    if shadow:
        dx, dy, blur, op = shadow
        sh, pad = shadow_of(layer, blur, op)
        _alpha(canvas, sh, x + dx - pad, y + dy - pad)
    _alpha(canvas, layer, x, y)


def _alpha(canvas, layer, x, y):
    cw, ch = canvas.size
    lw, lh = layer.size
    sx, sy = max(0, -x), max(0, -y)
    ex, ey = min(lw, cw - x), min(lh, ch - y)
    if ex <= sx or ey <= sy:
        return
    canvas.alpha_composite(layer.crop((sx, sy, ex, ey)), (x + sx, y + sy))


def glow(canvas, cx, cy, radius, color, strength=1.0):
    """Additive radial light."""
    size = int(radius * 2)
    yy, xx = np.mgrid[0:size, 0:size].astype(np.float32)
    d = np.sqrt((xx - radius) ** 2 + (yy - radius) ** 2) / radius
    f = np.clip(1 - d, 0, 1) ** 2.2 * strength
    layer = np.zeros((size, size, 3), np.float32)
    for i in range(3):
        layer[..., i] = color[i] * f
    x0, y0 = int(cx - radius), int(cy - radius)
    cw, ch = canvas.size
    sx, sy = max(0, -x0), max(0, -y0)
    ex, ey = min(size, cw - x0), min(size, ch - y0)
    if ex <= sx or ey <= sy:
        return
    region = np.asarray(canvas.crop((x0 + sx, y0 + sy, x0 + ex, y0 + ey)).convert("RGB")).astype(np.float32)
    region += layer[sy:ey, sx:ex]
    out = Image.fromarray(np.clip(region, 0, 255).astype(np.uint8), "RGB").convert("RGBA")
    canvas.paste(out, (x0 + sx, y0 + sy))


def gradient_rect(w, h, c0, c1, vertical=False):
    t = np.linspace(0, 1, h if vertical else w, dtype=np.float32)
    t = t[:, None] if vertical else t[None, :]
    arr = np.zeros((h, w, 3), np.float32)
    for i in range(3):
        arr[..., i] = c0[i] + (c1[i] - c0[i]) * t
    return to_img(arr)


# ----------------------------------------------------------------- leaves & plants
PALETTE = {
    "deep":  ((20, 52, 32), (58, 112, 58)),
    "mid":   ((28, 68, 38), (78, 134, 66)),
    "fresh": ((36, 82, 44), (104, 156, 76)),
}


def _beta(t, a, b, peak):
    t = min(max(t, 0.0), 1.0)
    top = (a / (a + b)) ** a * (b / (a + b)) ** b
    return peak * (t ** a) * ((1 - t) ** b) / top


def _profile(kind, t):
    if kind == "narrow":
        return _beta(t, 0.75, 0.95, 0.19)
    if kind == "round":
        return _beta(t, 0.5, 0.6, 0.40)
    return _beta(t, 0.55, 0.85, 0.46)          # pothos / heart-shaped, pointed tip


def leaf(kind, L, tone="mid", seed=0):
    """RGBA leaf pointing +x, base at (pad, centre)."""
    rnd = random.Random(seed)
    SS = 3
    pad = 6
    Wm = int(L * 0.62)
    w, h = L + pad * 2, Wm * 2 + pad * 2
    mask = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(mask)
    cy = h / 2
    lobes = [(0, 1.0)]
    if kind == "ivy":
        lobes = [(0, 1.0), (52, 0.62), (-52, 0.62), (100, 0.30), (-100, 0.30)]
    for ang, lf in lobes:
        pts_top, pts_bot = [], []
        n = 28
        for i in range(n + 1):
            t = i / n
            wd = _profile("narrow" if kind == "ivy" else kind, t) * L * (1.35 if kind == "ivy" else 1.0)
            if kind == "ivy":
                wd = wd * (0.9 + 0.1 * lf)
            x = t * L * lf
            pts_top.append((x, -wd * lf if kind == "ivy" else -wd))
            pts_bot.append((x, wd * lf if kind == "ivy" else wd))
        poly = pts_top + pts_bot[::-1]
        a = math.radians(ang)
        poly = [(pad + px * math.cos(a) - py * math.sin(a), cy + px * math.sin(a) + py * math.cos(a)) for px, py in poly]
        d.polygon([(px * SS, py * SS) for px, py in poly], fill=255)
    mask = mask.resize((w, h), Image.LANCZOS)
    m = np.asarray(mask).astype(np.float32) / 255.0

    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    dist = np.sqrt((xx - pad) ** 2 + (yy - cy) ** 2) / L
    c0, c1 = PALETTE[tone]
    tt = np.clip(dist, 0, 1)[..., None]
    col = np.array(c0, np.float32) + (np.array(c1, np.float32) - np.array(c0, np.float32)) * tt
    inner = np.asarray(mask.filter(ImageFilter.GaussianBlur(max(1.5, L * 0.045)))).astype(np.float32) / 255.0
    col *= (0.62 + 0.55 * inner)[..., None]                       # thickness: dark edges
    col *= (0.92 + 0.16 * noise(w, h, 4, 4, seed + 1))[..., None]  # mottling
    col += (noise(w, h, 2, 2, seed + 4)[..., None] - 0.5) * 6

    veins = Image.new("L", (w * SS, h * SS), 0)
    vd = ImageDraw.Draw(veins)
    for ang, lf in lobes:
        a = math.radians(ang)
        ex, ey = pad + L * lf * 0.96 * math.cos(a), cy + L * lf * 0.96 * math.sin(a)
        vd.line([(pad * SS, cy * SS), (ex * SS, ey * SS)], fill=255, width=max(2, int(L * 0.028 * SS)))
        if kind != "narrow":
            for k in (0.25, 0.45, 0.65, 0.82):
                bx, by = pad + (ex - pad) * k, cy + (ey - cy) * k
                for side in (-1, 1):
                    ba = a + side * math.radians(48)
                    ln = L * lf * 0.30 * (1 - k * 0.5)
                    vd.line([(bx * SS, by * SS), ((bx + ln * math.cos(ba)) * SS, (by + ln * math.sin(ba)) * SS)],
                            fill=150, width=max(1, int(L * 0.011 * SS)))
    veins = veins.resize((w, h), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.4))
    vm = (np.asarray(veins).astype(np.float32) / 255.0)[..., None]
    col = col * (1 - 0.55 * vm) + np.array([150, 190, 110], np.float32) * 0.55 * vm * 0.8
    spec = np.exp(-(((yy - cy + L * 0.10) / (L * 0.11)) ** 2)) * np.clip(1 - dist, 0, 1) * 0.10
    col += (spec * 255)[..., None] * 0.35

    out = np.dstack([np.clip(col, 0, 255), m * 255]).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def paste_leaf(canvas, lf, base_xy, angle_deg, shadow=True):
    """Paste a leaf (pointing +x) with its base at base_xy, rotated by angle (deg, clockwise on screen)."""
    w, h = lf.size
    big = Image.new("RGBA", (w * 2 + 8, w * 2 + 8), (0, 0, 0, 0))
    cx = cy = big.size[0] // 2
    big.alpha_composite(lf, (cx - 6, cy - h // 2))
    big = big.rotate(-angle_deg, Image.BICUBIC, center=(cx, cy))
    x, y = int(base_xy[0] - cx), int(base_xy[1] - cy)
    if shadow:
        sh, pad = shadow_of(big, 5, 0.38)
        _alpha(canvas, sh, x + 5 - pad, y + 8 - pad)
    _alpha(canvas, big, x, y)


def stem(draw, pts, width=3, color=(52, 70, 40)):
    draw.line(pts, fill=color, width=width, joint="curve")


def bezier(p0, p1, p2, n=24):
    out = []
    for i in range(n + 1):
        t = i / n
        out.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t * t * p2[0],
                    (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t * t * p2[1]))
    return out


def ivy_strand(canvas, x, y0, length, rnd, size=46, sway=22):
    """A hanging ivy vine with leaves alternating along it."""
    d = ImageDraw.Draw(canvas)
    pts = []
    for i in range(0, int(length), 8):
        pts.append((x + math.sin(i / 55 + x) * sway * (i / length + 0.2), y0 + i))
    stem(d, pts, 3)
    i = 14
    side = 1
    while i < length:
        px, py = pts[min(len(pts) - 1, int(i / 8))]
        s = size * (0.75 + 0.5 * rnd.random()) * (1.0 - 0.25 * i / length)
        tone = rnd.choice(["deep", "mid", "mid", "fresh"])
        lf = leaf("ivy", int(s), tone, seed=rnd.randint(0, 99999))
        ang = 90 + side * (40 + rnd.random() * 35) + rnd.uniform(-10, 10)
        paste_leaf(canvas, lf, (px, py), ang)
        side *= -1
        i += rnd.uniform(15, 26)


def cluster(canvas, cx, cy, n, spread, size, kind, rnd, up=1.0, tones=("deep", "mid", "mid", "fresh")):
    """A bushy plant head: stems fan out from (cx, cy)."""
    d = ImageDraw.Draw(canvas)
    items = []
    for _ in range(n):
        a = math.radians(rnd.uniform(-spread, spread) - 90 * up)
        r = rnd.uniform(0.3, 1.0)
        tip = (cx + math.cos(a) * size * 2.0 * r, cy + math.sin(a) * size * 2.0 * r * 1.0)
        items.append((r, tip, a))
    for r, tip, a in sorted(items, key=lambda t: t[0]):
        mid = ((cx + tip[0]) / 2 + rnd.uniform(-12, 12), (cy + tip[1]) / 2 + 6)
        stem(d, bezier((cx, cy), mid, tip), 3)
        s = int(size * (0.8 + 0.5 * rnd.random()))
        lf = leaf(kind, s, rnd.choice(tones), seed=rnd.randint(0, 99999))
        out_ang = math.degrees(a) + rnd.uniform(-35, 35) + (35 if tip[0] > cx else -35) * 0.4
        paste_leaf(canvas, lf, tip, out_ang + 0)


# ----------------------------------------------------------------- props
def cylinder(w, h, color, light=1.18, dark=0.62):
    """A vertical cylinder body (pot, mug, cup) with soft horizontal shading + rim."""
    x = np.linspace(-1, 1, w, dtype=np.float32)[None, :]
    shade = 0.30 + 0.70 * np.sqrt(np.clip(1 - x ** 2, 0, 1))
    shade = shade * (light - (light - dark) * np.clip((x + 0.15) * 0.8, 0, 1) ** 1.4)
    spec = np.exp(-((x + 0.35) / 0.10) ** 2) * 0.22
    arr = np.zeros((h, w, 3), np.float32)
    for i in range(3):
        arr[..., i] = color[i] * shade + 255 * spec
    arr += (noise(w, h, 3, 3, 5)[..., None] - 0.5) * 5
    img = to_img(arr).convert("RGBA")
    m = Image.new("L", (w, h), 0)
    ImageDraw.Draw(m).rounded_rectangle((0, 0, w - 1, h - 1), radius=max(3, w // 14), fill=255)
    img.putalpha(m)
    return img


def pot(w, h, color=(236, 232, 222), taper=0.84):
    """Tapered ceramic pot with elliptical rim."""
    body = cylinder(w, h, color)
    m = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(m)
    tw = int(w * taper)
    off = (w - tw) // 2
    d.polygon([(0, 0), (w, 0), (w - off, h), (off, h)], fill=255)
    body.putalpha(ImageChops.multiply(body.getchannel("A"), m))
    rim = Image.new("RGBA", (w, int(w * 0.22)), (0, 0, 0, 0))
    rd = ImageDraw.Draw(rim)
    rd.ellipse((0, 0, w - 1, rim.size[1] - 1), fill=tuple(int(c * 0.55) for c in color) + (255,))
    rd.ellipse((4, 3, w - 5, rim.size[1] - 3), fill=(52, 36, 24, 255))
    out = Image.new("RGBA", (w, h + rim.size[1] // 2), (0, 0, 0, 0))
    out.alpha_composite(body, (0, rim.size[1] // 2))
    out.alpha_composite(rim, (0, 0))
    return out


def book(w, h, color, rnd, label=True):
    """A standing book spine."""
    x = np.linspace(0, 1, w, dtype=np.float32)[None, :]
    shade = 0.84 + 0.22 * np.exp(-((x - 0.3) / 0.28) ** 2) - 0.20 * x ** 3
    arr = np.zeros((h, w, 3), np.float32)
    for i in range(3):
        arr[..., i] = color[i] * shade
    arr *= (0.94 + 0.10 * noise(w, h, 2, 2, rnd.randint(0, 999)))[..., None]
    img = to_img(arr).convert("RGBA")
    d = ImageDraw.Draw(img)
    if label and w > 14:
        by = int(h * rnd.uniform(0.18, 0.30))
        band = tuple(min(255, int(c * 1.5 + 30)) for c in color)
        d.rectangle((2, by, w - 3, by + max(3, h // 20)), fill=band + (255,))
        d.rectangle((2, int(h * 0.78), w - 3, int(h * 0.78) + 2), fill=band + (255,))
    d.line([(0, 0), (0, h)], fill=(0, 0, 0, 70), width=1)
    d.line([(w - 1, 0), (w - 1, h)], fill=(0, 0, 0, 90), width=2)
    d.rectangle((0, 0, w, 2), fill=(240, 230, 205, 255))   # page edge at the top
    return img


def book_row(canvas, x0, base_y, count, rnd, max_w=360, hmin=120, hmax=185, colors=None):
    colors = colors or [(150, 92, 62), (226, 214, 188), (74, 98, 86), (192, 150, 72), (58, 70, 98),
                        (170, 120, 110), (214, 198, 160), (92, 66, 52), (120, 140, 112)]
    x = x0
    for _ in range(count):
        bw = rnd.randint(18, 34)
        bh = rnd.randint(hmin, hmax)
        b = book(bw, bh, rnd.choice(colors), rnd)
        tilt = 0
        if rnd.random() < 0.12:
            tilt = rnd.choice([-5, 5])
            b = b.rotate(tilt, Image.BICUBIC, expand=True)
        put(canvas, b, (x, base_y - b.size[1]), shadow=(3, 2, 4, 0.5))
        x += bw + (b.size[0] - bw if tilt else 1)
        if x - x0 > max_w:
            break
    return x


def flat_books(canvas, x, base_y, rnd, n=3, w=130, colors=None):
    colors = colors or [(188, 130, 112), (226, 214, 188), (78, 104, 90), (196, 160, 86)]
    y = base_y
    for i in range(n):
        h = rnd.randint(20, 28)
        bw = w + rnd.randint(-14, 14)
        arr = np.zeros((h, bw, 3), np.float32)
        c = rnd.choice(colors)
        for k in range(3):
            arr[..., k] = c[k] * (0.9 + 0.1 * noise(bw, h, 3, 3, i + 4))
        img = to_img(arr).convert("RGBA")
        d = ImageDraw.Draw(img)
        d.rectangle((0, h - 7, bw, h), fill=(238, 228, 204, 255))      # pages
        d.line([(0, h - 8), (bw, h - 8)], fill=(120, 100, 80, 255), width=1)
        d.rectangle((0, 0, bw - 1, h - 1), outline=(0, 0, 0, 60))
        put(canvas, img, (x + rnd.randint(-5, 5), y - h), shadow=(2, 4, 5, 0.5))
        y -= h
    return y


def frame(w, h, rnd, wood_tex=None, print_kind="leaf"):
    """Wooden picture frame with a botanical print on cream mat."""
    t = max(8, w // 14)
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    fr = wood(w, h, seed=rnd.randint(0, 99), base=(176, 130, 84), ring=14).convert("RGBA")
    img.alpha_composite(fr)
    d = ImageDraw.Draw(img)
    d.rectangle((t, t, w - t, h - t), fill=(246, 240, 226, 255))
    d.rectangle((t, t, w - t, h - t), outline=(120, 90, 60, 255))
    d.rectangle((0, 0, w - 1, h - 1), outline=(60, 38, 20, 255))
    m = t * 2
    pr = Image.new("RGBA", (w - 2 * m, h - 2 * m), (250, 246, 236, 255))
    pd = ImageDraw.Draw(pr)
    pw, ph = pr.size
    cx = pw // 2
    pd.line([(cx, ph - 6), (cx, 12)], fill=(88, 110, 84, 255), width=2)
    for i in range(6):
        yy = ph - 16 - i * (ph - 36) / 6
        for side in (-1, 1):
            lw = pw * (0.34 - i * 0.025)
            pts = bezier((cx, yy), (cx + side * lw * 0.55, yy - 24), (cx + side * lw, yy - 8), 12)
            pts2 = bezier((cx, yy), (cx + side * lw * 0.55, yy + 10), (cx + side * lw, yy - 8), 12)
            pd.polygon(pts + pts2[::-1], fill=(104, 128, 96, 255), outline=(70, 92, 66, 255))
    img.alpha_composite(pr, (m, m))
    return img


def fairy_string(canvas, p0, p1, sag, rnd, bulbs=None, spacing=34):
    """Draws a drooping wire with bulbs; returns bulb positions."""
    mid = ((p0[0] + p1[0]) / 2, (p0[1] + p1[1]) / 2 + sag * 2)
    pts = bezier(p0, mid, p1, 120)
    d = ImageDraw.Draw(canvas)
    d.line(pts, fill=(48, 40, 30, 255), width=2)
    out = []
    acc = 0.0
    for i in range(1, len(pts)):
        acc += math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1])
        if acc >= spacing:
            acc = 0
            out.append(pts[i])
    return out
